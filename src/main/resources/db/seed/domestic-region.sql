-- 적재 기준:
--   * 특별시/광역시/세종 : 시도 단독. 자치구·자치군 모두 제외 (광역시는 시 단위까지만 커버)
--   * 도/특별자치도      : 시도 + 시/군 (행정구는 시로 흡수)
--   * 읍면동·리 전부 제외
--   * 전국(code 0000000000) : 법정동코드에 없는 합성 행. 아래 3) 참고
--   * 권역(code 01000000xx) : 여러 시도를 묶은 커버리지 단위(수도권). 합성 행. 아래 4) 참고
--
-- 이름 3종의 용도가 서로 다르다:
--   name         행정안전부 원본 명칭. 출처 대조용이며 화면에 쓰지 않는다.
--   short_name   드롭다운 항목용 자기 단계 이름   (경기 / 오산)
--   display_name 배지·카드·상세용 완성형          (경기 전역 / 경기 오산시)
--                시군구는 시/군 접미사를 붙인다 — 회사 소재지 카드 표기(시도+시군구)와 같은
--                형태로 맞춰, 소재지와 대응 지역이 한 화면에서 다른 표기로 보이지 않게 한다.
--                '경기 광주시'처럼 광역시와 이름이 겹치는 시군도 접미사로 구분된다.
-- display_name 을 저장해 두는 이유: 조회 응답은 회사에 연결된 지역을 평평한 목록으로
-- 돌려주므로 부모 문맥이 없다. 런타임에 조합하려면 카드 조회마다 부모 자기조인이
-- 붙는데, 172행짜리 고정 마스터에 컬럼 하나 두는 편이 싸고 표기 변경도 쉽다.
--
-- 적재 주체: ReferenceDataSeeder(ApplicationRunner). 컨텍스트 기동 완료 후 실행된다.
-- 멱등성: ON CONFLICT (code) DO UPDATE — 재기동 안전 + 표기 변경이 기존 행에도 반영된다.
--         (DO NOTHING 이면 이미 적재된 DB 는 새 컬럼이 NULL 로 남아 수동 갱신이 필요하다)
--         active 는 관리자가 토글하는 값이므로 덮어쓰지 않는다.
-- =====================================================================

-- 0) 정책 변경 정리 — 광역시 소속 자치군(기장/달성/군위/강화/옹진/울주) 제거.
--    "광역시는 시 단위까지" 로 정책이 바뀌어 더는 선택지로 제공하지 않는다.
--    구 시드로 이미 적재된 DB 를 정리하기 위한 일회성 문장이다. 모든 DB 가 한 번씩
--    기동을 마치면 이 블록은 통째로 지워도 된다.
--
--    조건 없이 지운다. 회사가 참조 중이면 FK 위반으로 기동이 실패하는데, 그게 의도다 —
--    조건부로 건너뛰면 표기 컬럼이 NULL 인 행이 조용히 남아 그 회사의 지역 배지가
--    null 로 나간다. 폐지 대상을 누가 쓰고 있다면 조용히 넘기지 말고 즉시 드러나야 한다.
